#!/usr/bin/env python3
"""Write models/quadruped.xml from the measured numbers. Needs no CAD files.

Inputs: models/geometry_measured.json, models/mass_measured.json, models/knee_linkage.json,
configs/robot.json. CI re-runs this and checks the committed XML is unchanged.

Model frame: x forward, y left, z up, metres. Joint zero: leg vertical, femur straight down,
tibia straight down. Signs: hip roll + = about +x; hip pitch and knee + = foot moves backward.

    python3 scripts/make_model.py            # write
    python3 scripts/make_model.py --check    # exit 1 if the committed XML differs
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
M = ROOT / "models"
GEOM = json.loads((M / "geometry_measured.json").read_text())
MASS = json.loads((M / "mass_measured.json").read_text())
LINK = json.loads((M / "knee_linkage.json").read_text())
CFG = json.loads((ROOT / "configs" / "robot.json").read_text())
SERVO = {k: v["value"] for k, v in json.loads((ROOT / "configs" / "servos.json").read_text())[CFG["servo_profile"]["value"]].items()
         if isinstance(v, dict) and "value" in v}   # the default profile; quad.model.load() can swap it
OUT = M / "quadruped.xml"

FEMUR_RADIUS_MM = 10.0   # femur STL is 20 x 23 mm in section
TIBIA_RADIUS_MM = 7.0    # tibia arm, inside the 25 mm wide tibia STL


def f(*v, k=6):
    return " ".join(f"{x:.{k}g}" if abs(x) >= 1e-12 else "0" for x in v)


def rot_y(v, t):
    c, s = math.cos(t), math.sin(t)
    return (c * v[0] + s * v[2], v[1], -s * v[0] + c * v[2])


def leg_points(g):
    """Joint and foot positions in each body's own frame (mm), at the zero pose."""
    s = 1.0 if g["side"] == "left" else -1.0
    pp, lat = g["plane_points_mm"], g["lateral_from_femur_servo_face_mm"]
    th = math.radians(MASS["cad_pose_deg"][LEG_OF[id(g)]]["hip_pitch"])
    ps = math.radians(MASS["cad_pose_deg"][LEG_OF[id(g)]]["tibia_abs"])
    K = (pp["K"][0], s * lat["K"], pp["K"][1])               # module axes, relative to H
    K0 = rot_y(K, -th)                                        # femur frame
    dFc = (pp["Fc"][0] - pp["K"][0], s * (lat["F"] - lat["K"]), pp["Fc"][1] - pp["K"][1])
    dF = (pp["F"][0] - pp["K"][0], s * (lat["F"] - lat["K"]), pp["F"][1] - pp["K"][1])
    return {"H": (0.0, s * g["roll_to_femur_servo_face_lateral_mm"], 0.0), "K": K0,
            "Fc": rot_y(dFc, -ps), "F": rot_y(dF, -ps), "s": s}


LEG_OF = {id(g): n for n, g in GEOM["legs"].items()}


def inertial(name, ind):
    b = MASS["bodies"][name]
    c = [x / 1000 for x in b["com_mm"]]
    I = [x * 1e-9 for x in b["inertia_g_mm2"]]               # g mm^2 -> kg m^2
    return (f'{ind}<inertial pos="{f(*c)}" mass="{b["mass_g"] / 1000:.6g}" '
            f'fullinertia="{f(*I)}"/>')


def main():
    frc = SERVO["forcerange_Nm"]
    kp = SERVO["kp_Nm_per_rad"]
    damp = SERVO["damping_Nm_s_per_rad"]
    arm = SERVO["armature_kg_m2"]
    fl = SERVO["frictionloss_Nm"]
    half = math.radians(CFG["servo_travel_deg"]["value"] / 2)
    margin = math.radians(CFG["joint_limit_margin_deg"]["value"])
    mu = CFG["foot_friction"]["value"]
    tb = MASS["bodies"]["torso"]["aabb_mm"]
    L = []
    w = L.append
    w('<!-- Generated by scripts/make_model.py from the measured numbers. Do not edit by hand. -->')
    w('<mujoco model="quadruped">')
    w('  <compiler angle="radian" autolimits="true"/>')
    w(f'  <option timestep="{CFG["timestep_s"]["value"]}" integrator="implicitfast"/>')
    w('  <size memory="10M"/>')
    w('  <visual><global offwidth="1280" offheight="960"/><headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3"/></visual>')
    w('  <asset>')
    w('    <texture name="grid" type="2d" builtin="checker" rgb1="0.85 0.85 0.85" rgb2="0.75 0.75 0.75" width="300" height="300"/>')
    w('    <material name="grid" texture="grid" texrepeat="8 8" reflectance="0.05"/>')
    w('    <material name="printed" rgba="0.95 0.55 0.15 1"/>')
    w('    <material name="servo" rgba="0.15 0.15 0.15 1"/>')
    w('    <material name="plate" rgba="0.75 0.77 0.8 1"/>')
    w('    <material name="foot" rgba="0.1 0.1 0.1 1"/>')
    w('  </asset>')
    w('  <default>')
    w(f'    <joint damping="{damp}" armature="{arm}" frictionloss="{fl}"/>')
    w('    <geom contype="1" conaffinity="1" condim="3" mass="0"/>')
    w(f'    <position kp="{kp}" forcerange="{-frc:.4g} {frc:.4g}" inheritrange="1"/>')
    w('  </default>')
    w('  <worldbody>')
    w(f'    <geom name="floor" type="plane" size="2 2 0.1" material="grid" friction="{mu} 0.005 0.0001"/>')
    w('    <light pos="0 -0.6 1.2" dir="0 0.4 -1" directional="true"/>')
    z0 = CFG["stand_hip_height_mm"]["value"] / 1000
    w(f'    <body name="torso" pos="0 0 {z0:.4g}">')
    w('      <freejoint name="root"/>')
    w(inertial("torso", "      "))
    c = [(tb[0][i] + tb[1][i]) / 2000 for i in range(3)]
    h = [(tb[1][i] - tb[0][i]) / 2000 for i in range(3)]
    h[1] = 0.057                                              # body side panels (gövde): 114 mm wide
    c[1] = 0.0
    w(f'      <geom name="torso" type="box" pos="{f(*c)}" size="{f(*h)}" material="plate"/>')
    b = GEOM["board_centroid_mm"]
    w(f'      <site name="imu" pos="{f(b[2] / 1000, b[0] / 1000, b[1] / 1000)}" size="0.005" rgba="0 0.6 1 1"/>')
    for leg, g in GEOM["legs"].items():
        P = leg_points(g)
        s = P["s"]
        hw = g["hip_world_mm"]
        lk = LINK[leg]
        hp0 = MASS["cad_pose_deg"][leg]["hip_pitch"]
        hb = MASS["bodies"][f"{leg}_hip"]["aabb_mm"]
        hc = [(hb[0][i] + hb[1][i]) / 2000 for i in range(3)]
        hh = [(hb[1][i] - hb[0][i]) / 2000 for i in range(3)]
        w(f'      <body name="{leg}_hip" pos="{f(hw[2] / 1000, hw[0] / 1000, hw[1] / 1000)}">')
        w(inertial(f"{leg}_hip", "        "))
        w(f'        <joint name="{leg}_hip_roll" axis="1 0 0" range="{-half:.4f} {half:.4f}"/>')
        w(f'        <geom name="{leg}_hip" type="box" pos="{f(*hc)}" size="{f(*hh)}" material="servo"/>')
        Hm = [x / 1000 for x in P["H"]]
        w(f'        <body name="{leg}_femur" pos="{f(*Hm)}">')
        w(inertial(f"{leg}_femur", "          "))
        lo, hi = math.radians(hp0) - half, math.radians(hp0) + half
        w(f'          <joint name="{leg}_hip_pitch" axis="0 1 0" range="{lo:.4f} {hi:.4f}"/>')
        K = [x / 1000 for x in P["K"]]
        w(f'          <geom name="{leg}_femur" type="capsule" fromto="0 {K[1]:.5g} 0 {f(*K)}" '
          f'size="{FEMUR_RADIUS_MM / 1000}" material="printed"/>')
        w(f'          <body name="{leg}_tibia" pos="{f(*K)}">')
        w(inertial(f"{leg}_tibia", "            "))
        # knee dead points: tibia lever parallel to the femur (q = lever offset, offset - 180 deg)
        off = -math.radians(180.0 + g["tibia_lever_to_foot_deg"])         # about -1.5 deg (checked with knee_linkage.solve)
        klo, khi = off - math.pi + margin, off - margin
        w(f'            <joint name="{leg}_knee" axis="0 1 0" range="{klo:.4f} {khi:.4f}" damping="0" armature="0" frictionloss="0"/>')
        Fc = [x / 1000 for x in P["Fc"]]
        r = g["foot_radius_mm"] / 1000
        w(f'            <geom name="{leg}_tibia" type="capsule" fromto="0 0 0 {f(Fc[0], Fc[1], Fc[2] + TIBIA_RADIUS_MM / 1000 + r)}" '
          f'size="{TIBIA_RADIUS_MM / 1000}" material="printed"/>')
        w(f'            <geom name="{leg}_foot" type="sphere" pos="{f(*Fc)}" size="{r:.5g}" material="foot" '
          f'friction="{mu} 0.005 0.0001"/>')
        w(f'            <site name="{leg}_foot" pos="{f(*Fc)}" size="{r * 1.3:.5g}" rgba="1 0 0 0.3"/>')
        w('          </body>')
        w('        </body>')
        w('      </body>')
        g["_knee_servo_range"] = [math.radians(x) for x in lk["usable_tibia_deg"]]
    w('    </body>')
    w('  </worldbody>')
    w('  <tendon>')
    for leg, g in GEOM["legs"].items():
        lo, hi = g["_knee_servo_range"]
        # the knee servo sets the tibia's pitch (hip pitch + knee): two parallelogram push-rods, 1:1 (docs/robot.md)
        w(f'    <fixed name="{leg}_knee_servo" range="{lo:.4f} {hi:.4f}" damping="{damp}" armature="{arm}" frictionloss="{fl}">')
        w(f'      <joint joint="{leg}_hip_pitch" coef="1"/>')
        w(f'      <joint joint="{leg}_knee" coef="1"/>')
        w('    </fixed>')
    w('  </tendon>')
    w('  <actuator>')
    for leg in GEOM["legs"]:
        w(f'    <position name="{leg}_hip_roll" joint="{leg}_hip_roll"/>')
        w(f'    <position name="{leg}_hip_pitch" joint="{leg}_hip_pitch"/>')
        w(f'    <position name="{leg}_knee" tendon="{leg}_knee_servo"/>')
    w('  </actuator>')
    w('  <sensor>')
    w('    <gyro name="imu_gyro" site="imu"/>')
    w('    <accelerometer name="imu_accel" site="imu"/>')
    w('    <framequat name="true_orientation" objtype="xbody" objname="torso"/>  <!-- analysis only: never a learner input -->')
    for leg in GEOM["legs"]:
        w(f'    <touch name="{leg}_contact" site="{leg}_foot"/>')
    for leg in GEOM["legs"]:
        for j in ("hip_roll", "hip_pitch", "knee"):
            w(f'    <actuatorfrc name="{leg}_{j}_torque" actuator="{leg}_{j}"/>')
    w('  </sensor>')
    w('</mujoco>')
    xml = "\n".join(L) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != xml:
            sys.exit("models/quadruped.xml is out of date: run python3 scripts/make_model.py")
        print("models/quadruped.xml is up to date")
        return
    OUT.write_text(xml)
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
